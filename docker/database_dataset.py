"""The base data set: derived from the local LIVE copy by a versioned recipe, anonymised, kept in Git.

The table registry gives each table its base rule: full (every row), slice (rows of the product
sample), faker (every row, personal columns replaced), empty or drop (no rows). The recipe adds
the product sample query and slice conditions for tables without an id_product column; the
project recipe (database/data/recipe.txt) wins over the profile one. Files are grouped by the
registry group, tables in name order, rows sorted by primary key, one row per line.
"""

import gzip
from pathlib import Path
import re
import tempfile

from database_schema import MANIFEST, database_tables, managed_file, mysql_query, schema_directory

DOCKER_ROOT = Path(__file__).resolve().parent
SET_NAME = re.compile(r'[a-z0-9][a-z0-9_-]*')
DEV_PASSWORD = 'dev12345'
# password_hash('dev12345', PASSWORD_BCRYPT): fixed, so regenerating the set changes nothing.
DEV_PASSWORD_BCRYPT = '$2y$12$bQCYcla.6XY4yiuyrokaj.CRjc38RaobTV3lozaoX4W4i6E/v3D0G'
CHUNK = 2000
HEADER = ('-- Base data set generated by setup (make db-dataset); do not edit by hand.\n'
          "SET NAMES utf8mb4;\nSET SESSION sql_mode = 'NO_AUTO_VALUE_ON_ZERO';\n"
          'SET SESSION foreign_key_checks = 0;\nSET SESSION unique_checks = 0;\n')
# Configuration values that are credentials; they never enter a data set.
SECRET_NAME = r'(PASSWORD$|PASSWD$|_PASS$|_PSWD|SECRET|TOKEN|API_KEY|APIKEY|_KEY$|SIGNATURE|CLIENTID|CLIENT_ID|MERCHANT_ID|_HASH$|^ADYEN_)'
# Settings whose names look like credentials but are switches or texts the shop needs.
SETTING_NAME = r'(_ENABLE$|_EXPIRY$|^PS_SECURITY_TOKEN$|^PS_SMARTY_CONSOLE_KEY$|^PS_CUSTOMER_SERVICE_SIGNATURE$)'


def dataset_directory(project, name):
    if not SET_NAME.fullmatch(name or ''):
        raise ValueError('Name the data set with set=dev (letters, digits, _ and -)')
    return schema_directory(project).parent / 'data' / name


def literal(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "''") + "'"


def identifier(value):
    return '`' + value.replace('`', '``') + '`'


def load_recipe(project):
    """(product sample SQL, [(table pattern, condition)]) from the project recipe, then the profile one."""
    from database_registry import prefix
    from fnmatch import fnmatchcase
    sources = [schema_directory(project).parent / 'data/recipe.txt']
    if project.settings.get('PROFILE') in ('ps', 'prestashop'):
        sources.append(DOCKER_ROOT / 'database-profile/prestashop/data-recipe.txt')
    products, conditions = None, []
    for path in sources:
        if not path.is_file():
            continue
        for number, raw in enumerate(path.read_text().splitlines(), 1):
            line = raw.strip()
            if not line or line.startswith('#'):
                continue
            line = line.replace('{p}', prefix(project))
            if line.startswith('@products '):
                products = products or line[len('@products '):].strip()
                continue
            pattern, _, condition = line.partition(' ')
            if not condition.strip():
                raise ValueError(f'{path.name}:{number}: expected "table condition" or "@products SELECT ..."')
            conditions.append((pattern, condition.strip()))
    return products, lambda table: next((c for p, c in conditions if fnmatchcase(table, p)), None)


def table_metadata(project):
    """Columns (name, type, nullable, generated) in order and primary key columns per table."""
    columns, keys = {}, {}
    rows = mysql_query(project, 'SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE, EXTRA FROM information_schema.COLUMNS '
                                'WHERE TABLE_SCHEMA = DATABASE() ORDER BY TABLE_NAME, ORDINAL_POSITION;\n')
    for line in rows.splitlines():
        table, column, kind, nullable, extra = (line.split('\t') + [''])[:5]
        columns.setdefault(table, []).append((column, kind, nullable == 'YES', 'GENERATED' in extra.upper()))
    rows = mysql_query(project, "SELECT TABLE_NAME, COLUMN_NAME FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE() "
                                "AND INDEX_NAME = 'PRIMARY' ORDER BY TABLE_NAME, SEQ_IN_INDEX;\n")
    for line in rows.splitlines():
        table, column = line.split('\t')
        keys.setdefault(table, []).append(column)
    return columns, keys


def anonymised(table, column, kind, nullable, key, legacy_key):
    """SQL expression replacing one personal column of a faker table, or None to keep it."""
    name = identifier(column)
    keep_null = (lambda expression: f'IF({name} IS NULL, NULL, {expression})') if nullable else (lambda expression: expression)
    numeric = kind in ('int', 'bigint', 'smallint', 'tinyint', 'mediumint', 'decimal', 'float', 'double')
    c = column.lower()
    person = 'employee' if table.endswith('employee') else 'customer'
    if c.endswith('_address') and kind in ('text', 'mediumtext', 'longtext', 'varchar', 'tinytext'):
        return keep_null("'Anonymised address'")
    if 'phone' in c and not numeric:
        return keep_null("'+37060000000'")
    if c in ('employee_firstname', 'employee_lastname'):
        return keep_null("'Dev'")
    if c == 'email':
        return keep_null(f"CONCAT('{person}', {key}, '@example.test')")
    if c in ('passwd', 'password'):
        hashed = literal(DEV_PASSWORD_BCRYPT) if legacy_key is None else f"MD5({literal(legacy_key + DEV_PASSWORD)})"
        return keep_null(hashed)
    if c == 'firstname':
        return keep_null("'Vardenis'")
    if c == 'lastname':
        return keep_null(f"CONCAT('Pavardenis ', {key})")
    if c == 'address1':
        return keep_null(f"CONCAT('Testo g. ', {key})")
    if c in ('address2', 'company', 'vat_number', 'dni', 'website', 'siret', 'ape', 'other', 'note'):
        return keep_null("''")
    if c == 'birthday':
        return keep_null("'1970-01-01'")
    if c in ('ip', 'ip_address', 'ip_registration_newsletter'):
        return keep_null('2130706433' if numeric else "'127.0.0.1'")
    if c == 'secure_key':
        return keep_null(f"MD5(CONCAT('dev', {key}))")
    if c in ('reset_password_token', 'reset_password_validity'):
        return 'NULL' if nullable else ("''" if not numeric else '0')
    if c in ('message', 'comment'):
        return keep_null("'Anonymised message'")
    return None


def select_sql(project, table, columns, keys, rule, condition, legacy_key):
    t = identifier(table)
    kept = [column for column in columns if not column[3]]
    key = identifier(keys[0]) if keys else '0'
    expressions = []
    for column, kind, nullable, _ in kept:
        expression = anonymised(table, column, kind, nullable, key, legacy_key) if rule == 'faker' else None
        if expression is None and (column.lower() in ('email', 'employee_firstname', 'employee_lastname')
                                   or 'phone' in column.lower()):
            # Contact details appear in configuration-like tables too (contacts, stores, supply history).
            expression = anonymised(table, column, kind, nullable, key, legacy_key)
        if table.endswith('configuration') and column == 'value' and any(c[0] == 'name' for c in kept):
            expression = (f"CASE WHEN `name` REGEXP {literal(SETTING_NAME)} THEN `value` "
                          f"WHEN `name` REGEXP {literal(SECRET_NAME)} THEN IF(`value` IS NULL, NULL, '') "
                          "WHEN `value` LIKE '%@%.%' THEN 'shop@example.test' ELSE `value` END")
        expressions.append(f'QUOTE({expression or identifier(column)})')
    order = ', '.join(identifier(k) for k in keys) or ', '.join(identifier(c[0]) for c in kept)
    where = f' WHERE {condition}' if condition else ''
    sql = f"SELECT CONCAT('(', CONCAT_WS(',', {', '.join(expressions)}), ')', CHAR(0)) FROM {t}{where} ORDER BY {order};\n"
    return [column[0] for column in kept], sql


def slice_condition(table, columns, products, recipe):
    explicit = recipe(table)
    if explicit:
        return explicit.replace('{products}', products)
    names = {column[0] for column in columns}
    if 'id_product' in names:
        return f'`id_product` IN {products}'
    raise ValueError(f'Slice table {table} has no id_product column; add a condition for it to database/data/recipe.txt')


def build_dataset(project, name='dev'):
    """Write the data set files from the local DB; returns {file name: bytes}."""
    from database_registry import classify, load, prefix
    from database_schema import registry_exclusions
    if project.environment != 'local':
        raise ValueError('Build the base data set from the local LIVE copy (ENV=local)')
    directory = dataset_directory(project, name)
    tables = database_tables(project)
    registry_exclusions(project, tables, require_classified=True)
    entries = load(project)
    sample_sql, recipe = load_recipe(project)
    if not sample_sql:
        raise ValueError('The recipe needs an @products line selecting the product sample')
    ids = [line for line in mysql_query(project, sample_sql.rstrip(';') + ';\n').split() if line.isdigit()]
    products = '(' + (','.join(ids) or '0') + ')'
    legacy_key = project.settings.get('PS_COOKIE_KEY', '') if str(project.settings.get('PS_VERSION', '')).startswith('1.6') else None
    columns, keys = table_metadata(project)
    groups, summary = {}, []
    for table in sorted(tables):
        _, group, rule, _ = classify(entries, table)
        if rule in ('empty', 'drop'):
            continue
        condition = slice_condition(table, columns[table], products, recipe) if rule == 'slice' else (
            (recipe(table) or '').replace('{products}', products) or None)
        names, sql = select_sql(project, table, columns[table], keys.get(table, []), rule, condition, legacy_key)
        output = mysql_query(project, sql, timeout=900, raw=True)
        rows = [row.lstrip(b'\n') for row in output.split(b'\x00') if row.strip(b'\n')]
        summary.append((table, rule, len(rows)))
        if not rows:
            continue
        columns_sql = ', '.join(identifier(column) for column in names)
        text = groups.setdefault(group, [HEADER.encode()])
        text.append(f'\n-- {table}: {rule}, {len(rows)} rows\n'.encode())
        for start in range(0, len(rows), CHUNK):
            chunk = rows[start:start + CHUNK]
            # One row per line keeps Git diffs to the rows that changed.
            text.append(f'INSERT INTO {identifier(table)} ({columns_sql}) VALUES\n'.encode()
                        + b',\n'.join(row.replace(b'\n', b'\\n').replace(b'\r', b'\\r') for row in chunk) + b';\n')
    files = {f'{group}.sql': b''.join(parts) for group, parts in sorted(groups.items())}
    if directory.is_symlink():
        raise ValueError('The data set directory must not be a symlink')
    directory.mkdir(parents=True, exist_ok=True)
    for stale in directory.glob('*.sql'):
        if stale.name not in files:
            stale.unlink()
    for file_name, content in files.items():
        target = directory / file_name
        if not target.exists() or target.read_bytes() != content:
            target.write_bytes(content)
    if legacy_key is not None:
        # PrestaShop 1.6 hashes passwords with the cookie key, so the set carries the key it was built with.
        (directory / 'dataset.env').write_text(f'PS_COOKIE_KEY={legacy_key}\n')
    raw = sum(len(content) for content in files.values())
    packed = sum(len(gzip.compress(content, mtime=0)) for content in files.values())
    rows = sum(count for _, _, count in summary)
    print(f'Data set {name}: {len(ids)} sample products, {sum(1 for s in summary if s[2])} tables, {rows} rows, '
          f'{raw / 1048576:.1f} MB ({packed / 1048576:.1f} MB gzip) in {directory}')
    print(f'Dev login: employee<id>@example.test / {DEV_PASSWORD} (every customer: customer<id>@example.test).')
    return files


def dataset_files(project, name):
    directory = dataset_directory(project, name)
    files = sorted(directory.glob('*.sql')) if directory.is_dir() else []
    if not files:
        raise ValueError(f'Data set {name} has no files in {directory}; build it with make db-dataset set={name}')
    for path in files:
        if path.is_symlink() or not path.is_file():
            raise ValueError(f'Data set file must be a regular file: {path}')
    return files


def schema_sql(project):
    """CREATE TABLE statements of the branch snapshot, in manifest order."""
    import json
    directory = schema_directory(project)
    manifest = json.loads((directory / MANIFEST).read_text())
    # PrestaShop tables carry zero-date defaults that strict modes refuse.
    return HEADER.encode() + b''.join(
        (directory / table['file']).read_bytes() for table in manifest['tables'] if managed_file(table['file']))


def plan_load(project, name):
    """Inputs of make db-load: one combined schema + data file, then after-import hooks and fixtures."""
    from database_import import after_import_hooks, render_hook
    files = dataset_files(project, name)
    if not (schema_directory(project) / MANIFEST).is_file():
        raise ValueError('The schema snapshot is missing; export and commit it first')
    hooks = after_import_hooks(project)
    fixtures = []
    if project.settings.get('FIXTURES_DIRECTORY'):
        from database_fixtures import plan_fixtures
        root = (project.root / project.settings['FIXTURES_DIRECTORY'])
        if (root / name).is_dir() or (root / 'common').is_dir():
            fixtures = plan_fixtures(project, name if (root / name).is_dir() else 'common')
    for path in [*hooks, *fixtures]:
        render_hook(project, path)
    return files, [*hooks, *fixtures]


def drop_all_tables(project):
    tables = database_tables(project)
    views = mysql_query(project, "SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() "
                                 "AND TABLE_TYPE = 'VIEW';\n").split()
    statements = ['SET SESSION foreign_key_checks = 0;']
    statements += [f'DROP VIEW IF EXISTS {identifier(view)};' for view in views]
    statements += [f'DROP TABLE IF EXISTS {identifier(table)};' for table in [*tables, 'setup_migrations']]
    mysql_query(project, '\n'.join(statements) + '\n', timeout=900)


def load_dataset(project, name='dev', replace=False, backup=False):
    from database_import import after_load, execute_sql
    files, hooks = plan_load(project, name)
    existing = database_tables(project)
    if existing and not replace:
        raise ValueError(f'Database {project.settings["DATABASE_NAME"]} has {len(existing)} tables; '
                         'replace=1 drops them first (add backup=1 to keep a copy)')
    output = project.directory / '.generated'
    output.mkdir(mode=0o700, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=output, suffix='.sql') as combined:
        combined.write(schema_sql(project))
        for path in files:
            combined.write(path.read_bytes())
        combined.flush()
        if existing:
            if backup:
                from database_backup import backup_database
                backup_database(project)
            drop_all_tables(project)
        execute_sql(project, [Path(combined.name), *hooks], first_is_dump=True)
    legacy = dataset_directory(project, name) / 'dataset.env'
    if legacy.is_file() and legacy.read_text().strip() != f'PS_COOKIE_KEY={project.settings.get("PS_COOKIE_KEY", "")}':
        print('Warning: this PrestaShop 1.6 set was built with another PS_COOKIE_KEY (see dataset.env); dev logins fail until they match.')
    after_load(project)
    print(f'Data set {name} loaded. Dev login: employee<id>@example.test / {DEV_PASSWORD}')
